//! Exact generated-helper source inverse; actual producer output stays retained.
#![expect(
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::panic,
    clippy::string_slice,
    reason = "closed test-source byte inverses fail at the exact malformed field"
)]

use sha2::{Digest, Sha256};
use std::fmt::Write;
use vize_carton::{String, ToCompactString};

pub struct Helper {
    pub before: String,
    pub after: String,
}

#[derive(Clone, Copy)]
#[allow(
    dead_code,
    reason = "CLI witness and TS-40 observers use different parts of this shared source inverse"
)]
pub struct Shift {
    start: usize,
    end: usize,
    delta: usize,
}

#[allow(
    dead_code,
    reason = "CLI witness retains the whole source; TS-40 additionally inverts every mapping endpoint"
)]
impl Shift {
    pub fn original(self, position: usize) -> usize {
        if position <= self.start {
            position
        } else {
            assert!(
                position >= self.end,
                "authored coordinate entered the synthetic helper"
            );
            position
                .checked_sub(self.delta)
                .expect("bounded helper offset")
        }
    }
}

fn hash(bytes: &[u8]) -> String {
    let mut result = String::with_capacity(64);
    for byte in Sha256::digest(bytes) {
        write!(result, "{byte:02x}").expect("in-memory digest");
    }
    result
}

pub fn helper() -> Helper {
    let bytes = include_bytes!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/_fixtures/differential/canon/release-js-pragma-opaque-slots/navigation-helper-successor.json"
    ));
    assert_eq!(
        hash(bytes),
        "558fa8bafc4b539bf6c6a3a3b242265eecb3786261e69db062eb815720910e9a"
    );
    let packet: serde_json::Value = serde_json::from_slice(bytes).expect("sealed helper packet");
    assert_eq!(packet["schema"], "vize.release-navigation-helper.successor");
    assert_eq!(packet["sourceOnly"], true);
    assert_eq!(packet["runtimeCredit"], false);
    assert_eq!(packet["beforeBytes"], 1138);
    assert_eq!(packet["afterBytes"], 1242);
    assert_eq!(packet["delta"], 104);
    let before = packet["before"]
        .as_str()
        .expect("whole old helper")
        .to_compact_string();
    let after = packet["after"]
        .as_str()
        .expect("whole current helper")
        .to_compact_string();
    assert_eq!(before.len(), 1138);
    assert_eq!(after.len(), 1242);
    let mut restored = after.clone();
    for clause in packet["inverse"]
        .as_array()
        .expect("finite helper inverse")
        .iter()
        .rev()
    {
        let start = clause[0].as_u64().expect("inverse start") as usize;
        let end = clause[1].as_u64().expect("inverse end") as usize;
        assert_eq!(
            &restored[start..end],
            clause[2].as_str().expect("whole new span")
        );
        restored.replace_range(start..end, clause[3].as_str().expect("whole old span"));
    }
    assert_eq!(restored, before);
    let producer = include_bytes!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../vize_canon/src/virtual_ts/scope/component_slots.rs"
    ));
    assert_eq!(packet["producer"]["after"]["sha256"], hash(producer));
    assert_eq!(packet["producer"]["after"]["bytes"], producer.len());
    assert_eq!(packet["producer"]["after"]["mode"], "100644");
    Helper { before, after }
}

pub fn restore(text: &str) -> (String, Option<Shift>) {
    let helper = helper();
    let Some(start) = text.find(&helper.after) else {
        assert!(
            !text.contains("__VizeEmptyVueNavigationSlots"),
            "partial or foreign helper"
        );
        assert!(
            !text.contains("__VizeNativeNavigationSlots"),
            "partial or foreign helper"
        );
        assert!(
            !text.contains("__VizeNavigationSlots"),
            "partial or foreign helper"
        );
        return (text.to_compact_string(), None);
    };
    assert_eq!(
        text.matches(&helper.after).count(),
        1,
        "one whole actual helper"
    );
    let restored = text.replacen(&helper.after, &helper.before, 1);
    assert_eq!(
        restored.replacen(&helper.before, &helper.after, 1),
        text,
        "whole generated byte inverse"
    );
    (
        restored.to_compact_string(),
        Some(Shift {
            start,
            end: start + helper.after.len(),
            delta: 104,
        }),
    )
}

/// Change only numeric generated ranges; punctuation and authored coordinates stay literal.
#[allow(
    dead_code,
    reason = "only the TS-40 observer needs serialized mapping inverses"
)]
pub fn ranges(text: &str, shift: Option<Shift>, left: bool) -> String {
    let Some(shift) = shift else {
        return text.to_compact_string();
    };
    let bytes = text.as_bytes();
    let mut edits = Vec::new();
    for (arrow, _) in text.match_indices('>') {
        let (start, colon, end) = if left {
            let mut colon = arrow;
            while colon > 0 && bytes[colon - 1].is_ascii_digit() {
                colon -= 1;
            }
            assert!(colon > 0 && bytes[colon - 1] == b':');
            colon -= 1;
            let mut start = colon;
            while start > 0 && bytes[start - 1].is_ascii_digit() {
                start -= 1;
            }
            (start, colon, arrow)
        } else {
            let start = arrow + 1;
            let mut colon = start;
            while colon < bytes.len() && bytes[colon].is_ascii_digit() {
                colon += 1;
            }
            assert!(colon < bytes.len() && bytes[colon] == b':');
            let mut end = colon + 1;
            while end < bytes.len() && bytes[end].is_ascii_digit() {
                end += 1;
            }
            (start, colon, end)
        };
        let first: usize = text[start..colon].parse().expect("first complete endpoint");
        let last: usize = text[colon + 1..end]
            .parse()
            .expect("last complete endpoint");
        assert!(first <= last);
        let mut replacement = String::default();
        write!(
            replacement,
            "{}:{}",
            shift.original(first),
            shift.original(last)
        )
        .expect("in-memory range");
        edits.push((start, end, replacement));
    }
    let mut result = text.to_compact_string();
    for (start, end, replacement) in edits.into_iter().rev() {
        result.replace_range(start..end, &replacement);
    }
    result
}
