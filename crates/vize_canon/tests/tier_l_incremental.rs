const FIXTURE_ID: &str = "vue-vben-admin";
const BUDGET_SCALE_ENV: &str = "VIZE_TIER_L_BUDGET_SCALE";
const TIER_L_VUE_FILES: usize = 500;
const INJECTED_FILE: &str = "apps/web-antd/src/__vize_batch_incremental_oracle__.vue";
const CLEAN_SOURCE: &str = r#"<script setup lang="ts">
const __vizeBatchIncrementalOracle: number = 1;
</script>

<template><span>{{ __vizeBatchIncrementalOracle }}</span></template>
"#;
const BROKEN_SOURCE: &str = r#"<script setup lang="ts">
const __vizeBatchIncrementalOracle: number = 'broken';
</script>

<template><span>{{ __vizeBatchIncrementalOracle }}</span></template>
"#;

#[derive(Deserialize)]
struct Registry {
    projects: Vec<RegistryProject>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct RegistryProject {
    id: String,
    revision: String,
    batch_incremental_budget: Option<BatchIncrementalBudget>,
}

struct InjectedFixtureFile(PathBuf);

impl InjectedFixtureFile {
    fn create(path: PathBuf) -> Self {
        assert!(!path.exists(), "injected fixture path must start absent");
        fs::write(&path, CLEAN_SOURCE).expect("clean fixture source should write");
        Self(path)
    }

    fn write(&self, source: &str) {
        fs::write(&self.0, source).expect("fixture patch should write");
    }
}

impl Drop for InjectedFixtureFile {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.0);
    }
}

#[test]
#[ignore = "runs the pinned Tier-L fixture in the per-PR Vue parity lane"]
fn vben_batch_incremental_session_reuses_exact_materialized_delta() {
    let repo_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let registry_path = repo_root.join("tests/_fixtures/vue-ecosystem-fixtures.json");
    let registry: Registry = serde_json::from_slice(
        &fs::read(registry_path).expect("fixture registry should be readable"),
    )
    .expect("fixture registry should parse");
    let project = registry
        .projects
        .into_iter()
        .find(|project| project.id == FIXTURE_ID)
        .expect("Vben fixture must be registered");
    let budget = project
        .batch_incremental_budget
        .expect("Vben must own a batchIncrementalBudget");
    assert_budget(&budget);
    let budget_scale = budget_scale();

    let fixture_root = env_path("VIZE_TIER_L_FIXTURE", &repo_root)
        .unwrap_or_else(|| repo_root.join("tests/_fixtures/_git/vue-vben-admin"))
        .canonicalize()
        .expect("Tier-L fixture path should canonicalize");
    assert_eq!(
        git_revision(&fixture_root),
        project.revision,
        "fixture revision drift"
    );
    let corsa_path = env_path("VIZE_TIER_L_CORSA_BIN", &repo_root).unwrap_or_else(|| {
        resolve_corsa_executable(CorsaResolveRequest {
            explicit_path: None,
            project_root: Some(&repo_root),
        })
        .expect("Corsa binary should resolve for Tier-L")
    });
    assert!(
        corsa_path.exists(),
        "Corsa binary is missing: {}",
        corsa_path.display()
    );
    capture_entry_world(&repo_root, &fixture_root, &corsa_path);

    let injected_path = fixture_root.join(INJECTED_FILE);
    let injected = InjectedFixtureFile::create(injected_path.clone());
    let options = BatchTypeCheckerOptions {
        tsconfig_path: Some(fixture_root.join("playground/tsconfig.json")),
        ..Default::default()
    };
    let mut checker =
        BatchTypeChecker::with_options_and_corsa_path(&fixture_root, options, Some(&corsa_path))
            .expect("Tier-L checker should start");

    let cold_started = Instant::now();
    let vue_paths = collect_vue_paths(&fixture_root);
    checker
        .scan_paths(&vue_paths)
        .expect("Tier-L scan should succeed");
    // Observe current generated bytes and planned paths, before either scale
    // assertion can unwind. This is not physical materialization or authored
    // source-byte evidence. All capture cost stays in the original cold timer.
    let files = checker.virtual_files();
    let rows = files
        .iter()
        .enumerate()
        .map(|(ordinal, file)| {
            serde_json::json!({
                "ordinal": ordinal, "originalPath": file.original_path,
                "plannedVirtualPath": file.virtual_path, "generatedBytes": file.content.as_bytes(),
                "byteLength": file.content.len(), "sha256": vize_s0::cstr!("{:x}", Sha256::digest(file.content.as_bytes())),
            })
        })
        .collect::<Vec<_>>();
    write_capture(
        &repo_root,
        "scan-membership.json",
        &serde_json::json!({
            "schemaVersion": 1, "boundary": "after-original-scan-before-both-membership-assertions",
            "fixtureRoot": fixture_root, "fixtureRevision": project.revision,
            "selectedRoots": vue_paths, "fileCount": checker.file_count(),
            "rows": rows, "authority": "scan membership/current generated bytes/planned virtual paths only",
        }),
    );
    capture_scan_disk(
        &repo_root,
        vue_paths
            .iter()
            .cloned()
            .chain(files.iter().map(|file| file.original_path.clone())),
    );
    assert_eq!(files.len(), checker.file_count(), "capture lost scan rows");
    assert_eq!(
        checker
            .virtual_files()
            .iter()
            .filter(|file| file
                .original_path
                .extension()
                .is_some_and(|extension| extension == "vue"))
            .count(),
        TIER_L_VUE_FILES,
        "fixture must remain Tier-L scale"
    );
    // The 500 Vue roots import 181 TypeScript sources. They now participate in
    // the canonical graph instead of being bypassed through filesystem reads.
    assert_eq!(checker.file_count(), budget.max_requested_files);
    for path in &vue_paths {
        assert!(
            checker
                .virtual_files()
                .iter()
                .any(|file| &file.original_path == path)
        );
    }
    let cold = checker
        .check_incremental(std::slice::from_ref(&injected_path))
        .expect("cold incremental session should complete");
    let cold_ms = cold_started.elapsed().as_millis();
    assert_no_injected_diagnostics(&cold);
    let cold_metrics = checker.incremental_metrics();
    assert_cold_metrics(cold_metrics, &budget);
    assert_within_budget("cold", cold_ms, budget.cold_ms, budget_scale);

    injected.write(BROKEN_SOURCE);
    let broken_started = Instant::now();
    let broken = checker
        .check_incremental(std::slice::from_ref(&injected_path))
        .expect("broken warm check should complete");
    let broken_ms = broken_started.elapsed().as_millis();
    let injected_errors = broken
        .diagnostics
        .iter()
        .filter(|diagnostic| {
            diagnostic.file.file_name().and_then(|name| name.to_str())
                == Some("__vize_batch_incremental_oracle__.vue")
                && diagnostic.code == Some(2322)
        })
        .collect::<Vec<_>>();
    assert_eq!(
        injected_errors.len(),
        1,
        "broken patch must report exactly one injected TS2322"
    );
    assert_eq!((injected_errors[0].line, injected_errors[0].column), (1, 6));
    assert!(
        injected_errors[0]
            .message
            .contains("not assignable to type 'number'"),
        "unexpected injected TS2322: {}",
        injected_errors[0].message
    );
    let broken_metrics = checker.incremental_metrics();
    assert_warm_metrics(broken_metrics, 2, 1, &budget);
    assert_within_budget("broken warm", broken_ms, budget.warm_ms, budget_scale);

    injected.write(CLEAN_SOURCE);
    let repaired_started = Instant::now();
    let repaired = checker
        .check_incremental(std::slice::from_ref(&injected_path))
        .expect("repaired warm check should complete");
    let repaired_ms = repaired_started.elapsed().as_millis();
    assert_no_injected_diagnostics(&repaired);
    let repaired_metrics = checker.incremental_metrics();
    assert_warm_metrics(repaired_metrics, 3, 2, &budget);
    assert_within_budget("repaired warm", repaired_ms, budget.warm_ms, budget_scale);

    let artifact = Artifact {
        schema_version: 1,
        fixture: FixtureEvidence {
            id: FIXTURE_ID,
            revision: project.revision,
            injected_file: INJECTED_FILE,
        },
        budget,
        budget_scale,
        file_count: checker.file_count(),
        lanes: vec![
            lane("cold", cold_ms, cold_metrics),
            lane("brokenWarm", broken_ms, broken_metrics),
            lane("repairedWarm", repaired_ms, repaired_metrics),
        ],
    };
    write_artifact(&repo_root, &artifact);
}

fn collect_vue_paths(fixture_root: &Path) -> Vec<PathBuf> {
    let mut paths = ["apps", "packages", "playground"]
        .into_iter()
        .flat_map(|relative| walkdir::WalkDir::new(fixture_root.join(relative)))
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().is_file())
        .map(walkdir::DirEntry::into_path)
        .filter(|path| path.extension().and_then(|extension| extension.to_str()) == Some("vue"))
        .collect::<Vec<_>>();
    paths.sort();
    assert!(
        paths.len() > TIER_L_VUE_FILES,
        "pinned fixture fell below Tier-L scale"
    );
    paths.truncate(TIER_L_VUE_FILES);
    assert!(paths.iter().any(|path| path.ends_with(INJECTED_FILE)));
    paths
}

fn write_capture(repo_root: &Path, name: &str, value: &serde_json::Value) {
    let directory = env_path("VIZE_TIER_L_METRICS_DIR", repo_root)
        .unwrap_or_else(|| repo_root.join("target/vize-tests/metrics/vben-batch-incremental"));
    fs::create_dir_all(&directory).expect("capture directory should exist");
    fs::write(
        directory.join(name),
        serde_json::to_vec(value).expect("capture paths and values must serialize without loss"),
    )
    .expect("complete capture should write before assertions");
}

fn capture_scan_disk(repo_root: &Path, paths: impl Iterator<Item = PathBuf>) {
    let directory = env_path("VIZE_TIER_L_METRICS_DIR", repo_root)
        .unwrap_or_else(|| repo_root.join("target/vize-tests/metrics/vben-batch-incremental"))
        .join("after-scan-disk");
    fs::create_dir_all(&directory).unwrap();
    let rows = paths.enumerate().map(|(ordinal, path)| {
        let metadata = fs::symlink_metadata(&path);
        let symlink = metadata.as_ref().ok().filter(|m| m.file_type().is_symlink())
            .map(|_| fs::read_link(&path).map_err(|error| error.to_string()));
        let mut row = serde_json::json!({
            "ordinal": ordinal, "lexicalPath": path, "symlinkTarget": symlink,
            "metadata": metadata.map(|m| serde_json::json!({"file": m.is_file(), "directory": m.is_dir(), "symlink": m.file_type().is_symlink(), "byteLength": m.len()})).map_err(|error| error.to_string()),
        });
        row["diskObservation"] = match fs::read(&path) {
            Ok(bytes) => {
                let retained = directory.join(vize_s0::cstr!("{ordinal}.bin").as_str());
                fs::write(&retained, &bytes).unwrap();
                serde_json::json!({"status": "read", "bodyPath": retained, "byteLength": bytes.len(), "sha256": vize_s0::cstr!("{:x}", Sha256::digest(&bytes))})
            }
            Err(error) => serde_json::json!({
                "status": if error.kind() == std::io::ErrorKind::NotFound { "absent" } else { "read-error" },
                "errorKind": vize_s0::cstr!("{:?}", error.kind()), "osCode": error.raw_os_error(), "message": error.to_string(),
            }),
        };
        row
    }).collect::<Vec<_>>();
    write_capture(
        repo_root,
        "after-scan-disk-observations.json",
        &serde_json::json!({
            "boundary": "fresh-after-scan-disk-observation-not-consumed-authored-bytes",
            "sourceOrder": "all original selected roots then every scan row original path; duplicates retained",
            "rows": rows,
        }),
    );
}

fn capture_entry_world(repo_root: &Path, fixture_root: &Path, corsa_path: &Path) {
    let git = |arguments: &[&str]| {
        let output = std::process::Command::new("git")
            .arg("-C")
            .arg(fixture_root)
            .args(arguments)
            .output()
            .expect("fixture Git authority should be available");
        assert!(output.status.success(), "fixture Git authority failed");
        output.stdout
    };
    let toplevel = git(&["rev-parse", "--show-toplevel"]);
    assert_eq!(
        Path::new(std::str::from_utf8(&toplevel).unwrap().trim())
            .canonicalize()
            .unwrap(),
        fixture_root,
        "fixture Git commands must not fall back to the enclosing repository"
    );
    let entries = walkdir::WalkDir::new(fixture_root)
        .follow_links(false)
        .sort_by_file_name()
        .into_iter()
        .map(|entry| {
            let entry = entry.expect("complete fixture inventory must not omit walk errors");
            let path = entry.path();
            let metadata = fs::symlink_metadata(path).expect("fixture metadata should read");
            #[cfg(unix)]
            let mode = {
                use std::os::unix::fs::MetadataExt;
                Some(metadata.mode())
            };
            #[cfg(not(unix))]
            let mode: Option<u32> = None;
            let bytes = metadata.is_file().then(|| fs::read(path).unwrap());
            serde_json::json!({
                "path": path, "modeUnix": mode,
                "directory": metadata.is_dir(),
                "symlinkTarget": metadata.file_type().is_symlink().then(|| fs::read_link(path).unwrap()),
                "diskByteLength": bytes.as_ref().map(Vec::len), "diskSha256": bytes.as_ref().map(|bytes| vize_s0::cstr!("{:x}", Sha256::digest(bytes))),
            })
        })
        .collect::<Vec<_>>();
    let executable = corsa_path
        .canonicalize()
        .expect("explicit provider should canonicalize");
    let bytes = fs::read(&executable).expect("complete native executable should hash");
    let package = executable
        .ancestors()
        .skip(1)
        .map(|directory| directory.join("package.json"))
        .find(|path| path.is_file())
        .expect("native executable must have an identifiable package owner");
    let package_bytes = fs::read(&package).expect("provider package should read");
    write_capture(
        repo_root,
        "tier-l-entry-world.json",
        &serde_json::json!({
            "boundary": "tier-l-entry-after-original-predecessors-before-injected-file-and-cold-timer",
            "fixtureRoot": fixture_root,
            "gitToplevelBytes": toplevel, "gitRevisionBytes": git(&["rev-parse", "HEAD"]),
            "gitStatusBytes": git(&["status", "--porcelain=v1", "--untracked-files=all", "-z"]),
            "fixtureDiskObservations": entries,
            "nativeExecutable": {"path": executable, "byteLength": bytes.len(), "sha256": vize_s0::cstr!("{:x}", Sha256::digest(&bytes))},
            "providerPackage": {"path": package, "bytes": package_bytes, "sha256": vize_s0::cstr!("{:x}", Sha256::digest(&package_bytes))},
            "providerScope": "explicit executable and owning package only; other installed node_modules are not authenticated",
            "authoredAuthority": "fresh disk observations only; not original bytes consumed by scan",
            "processArgv": std::env::args().collect::<Vec<_>>(), "processCwd": std::env::current_dir().unwrap(),
            "executionEnvironment": std::env::vars().filter(|(name, _)| [
                "RAYON_NUM_THREADS", "GOMAXPROCS", "NODE_OPTIONS", "RUSTUP_TOOLCHAIN",
                "VIZE_TIER_L_FIXTURE", "VIZE_TIER_L_CORSA_BIN", "VIZE_TIER_L_METRICS_DIR",
                "VIZE_TIER_L_BUDGET_SCALE", "VIZE_RUNTIME_NODE_MODULES", "CARGO_BUILD_PROFILE",
            ].contains(&name.as_str())).collect::<Vec<_>>(),
        }),
    );
}

fn assert_budget(budget: &BatchIncrementalBudget) {
    assert!((1..=300_000).contains(&budget.cold_ms));
    assert!((1..=budget.cold_ms).contains(&budget.warm_ms));
    assert!((1..=10_000).contains(&budget.max_requested_files));
    assert_eq!(
        budget.max_changed_files, 1,
        "one edited SFC must remain the delta budget"
    );
}

fn budget_scale() -> f64 {
    match std::env::var(BUDGET_SCALE_ENV) {
        Ok(raw) if raw.is_empty() => 1.0,
        Ok(raw) => {
            let scale = raw.parse::<f64>().unwrap_or_else(|_| {
                panic!(
                    "{BUDGET_SCALE_ENV} must be a finite number greater than 0 and at most 100, got {raw:?}"
                )
            });
            assert!(
                scale.is_finite() && scale > 0.0 && scale <= 100.0,
                "{BUDGET_SCALE_ENV} must be a finite number greater than 0 and at most 100, got {raw:?}"
            );
            scale
        }
        Err(std::env::VarError::NotPresent) => 1.0,
        Err(error) => panic!("{BUDGET_SCALE_ENV} must be valid UTF-8: {error}"),
    }
}

fn assert_no_injected_diagnostics(result: &vize_canon::BatchTypeCheckResult) {
    assert!(
        result.diagnostics.iter().all(|diagnostic| {
            diagnostic.file.file_name().and_then(|name| name.to_str())
                != Some("__vize_batch_incremental_oracle__.vue")
        }),
        "clean source retained injected-file diagnostics"
    );
}

fn assert_cold_metrics(metrics: IncrementalCheckMetrics, budget: &BatchIncrementalBudget) {
    assert_eq!((metrics.checks, metrics.session_starts), (1, 1));
    assert_eq!((metrics.session_reuses, metrics.session_refreshes), (0, 0));
    assert_eq!(metrics.session_to_cli_fallbacks, 0);
    assert!(metrics.last_session_started);
    assert!(!metrics.last_session_to_cli_fallback);
    assert_eq!(
        (
            metrics.last_changed_files,
            metrics.last_created_files,
            metrics.last_deleted_files
        ),
        (0, 0, 0)
    );
    assert_requested_budget(metrics, budget);
}

fn assert_warm_metrics(
    metrics: IncrementalCheckMetrics,
    checks: usize,
    reuses: usize,
    budget: &BatchIncrementalBudget,
) {
    assert_eq!((metrics.checks, metrics.session_starts), (checks, 1));
    assert_eq!(
        (metrics.session_reuses, metrics.session_refreshes),
        (reuses, reuses)
    );
    assert_eq!(metrics.session_to_cli_fallbacks, 0);
    assert!(metrics.last_session_reused && metrics.last_session_refreshed);
    assert!(!metrics.last_session_to_cli_fallback);
    assert_eq!(metrics.last_changed_files, budget.max_changed_files);
    assert_eq!(
        (metrics.last_created_files, metrics.last_deleted_files),
        (0, 0)
    );
    assert_requested_budget(metrics, budget);
}

fn assert_requested_budget(metrics: IncrementalCheckMetrics, budget: &BatchIncrementalBudget) {
    assert!(metrics.last_requested_files > 0);
    assert_eq!(
        metrics.last_requested_files, budget.max_requested_files,
        "the pinned Tier-L corpus must request every registered source, including dependencies"
    );
    assert!(
        metrics.last_requested_files <= budget.max_requested_files,
        "requested {} files, budget is {}",
        metrics.last_requested_files,
        budget.max_requested_files
    );
}

fn assert_within_budget(lane: &str, elapsed_ms: u128, budget_ms: u64, budget_scale: f64) {
    let scaled_budget_ms = (budget_ms as f64 * budget_scale).ceil() as u128;
    assert!(
        elapsed_ms < scaled_budget_ms,
        "{lane} took {elapsed_ms}ms, budget is {budget_ms}ms at scale {budget_scale} ({scaled_budget_ms}ms)"
    );
}
