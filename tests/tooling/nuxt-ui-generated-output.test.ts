function temporary(run: (root: string) => void) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nuxt-generated-output-law-"));
  try {
    run(root);
  } finally {
    fs.rmSync(root, { recursive: true });
  }
}
function file(root: string, name: string, bytes: string | Buffer) {
  const target = path.join(root, name);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, bytes);
}
function fixture(root: string) {
  file(
    root,
    "package.json",
    JSON.stringify({
      scripts: {
        "dev:prepare":
          "nuxt-module-build build --stub && nuxt-module-build prepare && nuxt prepare playgrounds/nuxt && nuxt prepare docs && pnpm dev:vue:build",
        "dev:vue:build": "pnpm --filter './playgrounds/vue' build",
      },
    }),
  );
  file(root, "playgrounds/vue/dist/whole.bin", Buffer.from([0, 10, 13, 128, 255]));
  file(root, "src/whole.vue", "authored\r\nbytes");
}
function identity(root: string) {
  const stat = fs.statSync(root);
  return {
    cwd: root,
    inode: stat.ino,
    device: stat.dev,
    providers: [],
    source: sourceInventory(root, new Set()),
    fixture: { whole: "source pin" },
  };
}

test("only exact command-bound Vue playground outputs differ, with all raw bodies retained", () =>
  temporary((root) => {
    const cwd = path.join(root, "fixture");
    fixture(cwd);
    const before = identity(cwd);
    const retained = retainNuxtUiGeneratedOutput(cwd, path.join(root, "before"), before);
    assert.equal(retained.namespace, "playgrounds/vue/dist");
    assert.deepEqual(
      fs.readFileSync(path.join(root, "before/bodies/playgrounds/vue/dist/whole.bin")),
      Buffer.from([0, 10, 13, 128, 255]),
    );
    file(cwd, "playgrounds/vue/dist/whole.bin", "next complete bytes");
    file(cwd, "playgrounds/vue/dist/new.js", "generated new body");
    const after = identity(cwd);
    retainNuxtUiGeneratedOutput(cwd, path.join(root, "after"), after);
    const delta = compareNuxtUiAuthoredIdentity(before, after);
    assert.deepEqual(
      delta.map((entry) => entry.path),
      ["playgrounds/vue/dist/new.js", "playgrounds/vue/dist/whole.bin"],
    );
    assert.deepEqual(
      fs.readFileSync(path.join(root, "after/bodies/playgrounds/vue/dist/whole.bin")),
      Buffer.from("next complete bytes"),
    );
    for (const name of [
      "src/whole.vue",
      "other/dist/generated.js",
      "playgrounds/vue/dist-sibling/whole.js",
    ]) {
      const old = fs.existsSync(path.join(cwd, name))
        ? fs.readFileSync(path.join(cwd, name))
        : null;
      file(cwd, name, "unallowed change");
      assert.throws(() => compareNuxtUiAuthoredIdentity(before, identity(cwd)), /authored source/);
      if (old) file(cwd, name, old);
      else fs.rmSync(path.join(cwd, name));
    }
    const changedProviders = {
      ...after,
      providers: [
        {
          name: "vue",
          directory: "/changed",
          inode: 1,
          device: 1,
          version: "different",
          files: [],
        },
      ],
    };
    assert.throws(() => compareNuxtUiAuthoredIdentity(before, changedProviders), /provider bytes/);
  }));

test("generated body custody refuses changed producer commands and symlinked output", () =>
  temporary((root) => {
    const cwd = path.join(root, "fixture");
    fixture(cwd);
    const manifest = fs.readFileSync(path.join(cwd, "package.json"));
    file(cwd, "package.json", JSON.stringify({ scripts: { "dev:prepare": "unreviewed build" } }));
    assert.throws(
      () => retainNuxtUiGeneratedOutput(cwd, path.join(root, "wrong-command"), identity(cwd)),
      /prepare command/,
    );
    file(cwd, "package.json", manifest);
    file(cwd, "owned-source.txt", "must not substitute for generated bytes");
    fs.rmSync(path.join(cwd, "playgrounds/vue/dist/whole.bin"));
    fs.symlinkSync("../../../owned-source.txt", path.join(cwd, "playgrounds/vue/dist/whole.bin"));
    assert.throws(
      () => retainNuxtUiGeneratedOutput(cwd, path.join(root, "linked"), identity(cwd)),
      /ordinary owned bytes/,
    );
    assert.equal(
      fs.readFileSync(path.join(cwd, "owned-source.txt"), "utf8"),
      "must not substitute for generated bytes",
    );
  }));

type GraphModule = {
  id: string;
  url: string;
  file: string;
  importedModules: Set<GraphModule>;
  importers: Set<GraphModule>;
};
function module(id: string): GraphModule {
  return { id, url: id, file: id, importedModules: new Set(), importers: new Set() };
}

test("module graph observation is passive and retains complete edge closure at close", () =>
  temporary((root) => {
    const select = module("/fixture/src/runtime/components/Select.vue");
    const primitive = module("/fixture/node_modules/reka-ui/Primitive.js");
    select.importedModules.add(primitive);
    primitive.importers.add(select);
    const graph = { idToModuleMap: new Map([[select.id, select]]) };
    const before = graph.idToModuleMap;
    const hooks: Partial<ModuleGraphHooks> = {};
    observeNuxtUiModuleGraphs(
      {
        onServer(callback) {
          hooks["vite:serverCreated"] = callback;
        },
        onClose(callback) {
          hooks.close = callback;
        },
      },
      root,
    );
    assert.ok(hooks["vite:serverCreated"] && hooks.close);
    hooks["vite:serverCreated"]({ moduleGraph: graph }, { isServer: true });
    assert.equal(fs.existsSync(path.join(root, "module-graphs.json")), false);
    hooks.close();
    assert.equal(graph.idToModuleMap, before);
    assert.equal(graph.idToModuleMap.size, 1);
    assert.deepEqual([...select.importedModules], [primitive]);
    const actual = JSON.parse(fs.readFileSync(path.join(root, "module-graphs.json"), "utf8"));
    assert.deepEqual(
      actual.graphs[0].modules.map((entry: { id: string }) => entry.id),
      [select.id, primitive.id],
    );
    assert.deepEqual(
      actual.graphs[0].modules.map((entry: { importedModules: number[]; importers: number[] }) => [
        entry.importedModules,
        entry.importers,
      ]),
      [
        [[1], []],
        [[], [0]],
      ],
    );
  }));

test("output non-use needs both actual Select graphs and refuses any output id, edge or physical alias", () =>
  temporary((root) => {
    const cwd = path.join(root, "fixture");
    fixture(cwd);
    const select = module(path.join(cwd, "src/runtime/components/Select.vue"));
    const graph = snapshotNuxtUiModuleGraph({ idToModuleMap: new Map([[select.id, select]]) });
    const write = (extra: unknown[] = []) => {
      for (const phase of ["candidate", "reference"])
        file(
          root,
          `${phase}/session-1/module-graphs-live.json`,
          JSON.stringify({
            schema: 1,
            live: true,
            pid: 1,
            graphs: [
              { lane: { isClient: true }, environment: null, ...graph },
              { lane: { isServer: true }, environment: null, ...graph },
              ...extra,
            ],
          }),
        );
    };
    write();
    assert.equal(verifyNuxtUiGeneratedOutputUnused(root, cwd).phases.length, 2);
    const lookalike = structuredClone(graph);
    Object.assign(lookalike.modules[0]!, { id: `${select.id}-unrelated`, file: null });
    file(
      root,
      "reference/session-1/module-graphs-live.json",
      JSON.stringify({
        schema: 1,
        live: true,
        pid: 1,
        graphs: [
          { lane: { isClient: true }, environment: null, ...lookalike },
          { lane: { isServer: true }, environment: null, ...lookalike },
        ],
      }),
    );
    assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /both lanes/);
    write();
    fs.rmSync(path.join(root, "reference/session-1/module-graphs-live.json"));
    file(root, "reference/session-1/module-graphs.json", JSON.stringify({ schema: 1, graphs: [] }));
    assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /both lanes/);
    for (const field of ["id", "url", "file", "realFile"]) {
      const bad = structuredClone(graph);
      Object.assign(bad.modules[0]!, { [field]: path.join(cwd, "playgrounds/vue/dist/whole.bin") });
      write([{ lane: { isServer: true }, environment: null, ...bad }]);
      assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /uses generated/);
    }
    const alias = structuredClone(graph);
    alias.entries[0]!.id = path.join(cwd, "playgrounds/vue/dist/whole.bin");
    write([{ lane: { isServer: true }, environment: null, ...alias }]);
    assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /uses generated/);
    alias.entries[0]!.id = `${cwd}/playgrounds/vue/other/../dist/whole.bin`;
    write([{ lane: { isServer: true }, environment: null, ...alias }]);
    assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /uses generated/);
    const broken = structuredClone(graph);
    broken.modules[0]!.importedModules = [99];
    write([{ lane: { isServer: true }, environment: null, ...broken }]);
    assert.throws(() => verifyNuxtUiGeneratedOutputUnused(root, cwd), /edge closure/);
  }));

test("whole home and button authorities compare separately without changing response bytes", () =>
  temporary((root) => {
    for (const phase of ["candidate", "reference"])
      for (const name of ["home", "button"])
        file(
          root,
          `${phase}/html-${name}-1/normalized.html`,
          `<!doctype html>\r\n<!--${name}-->完整`,
        );
    file(root, "candidate/html-home-2/normalized.html", "<!doctype html>\r\n<!--home-->完整");
    const result = summarizeNuxtUiWholeHtml(root);
    assert.equal(result.wholeHtmlEqual, true);
    assert.deepEqual(
      result.routes.map(({ name, phases, wholeHtmlEqual }) => ({
        name,
        counts: phases.map(({ files }) => files.length),
        wholeHtmlEqual,
      })),
      [
        { name: "home", counts: [2, 1], wholeHtmlEqual: true },
        { name: "button", counts: [1, 1], wholeHtmlEqual: true },
      ],
    );
    file(root, "candidate/html-home-2/normalized.html", "<!doctype html>\n<!--home-->完整");
    assert.equal(
      summarizeNuxtUiWholeHtml(root).wholeHtmlEqual,
      false,
      "CRLF bytes cannot be normalized",
    );
    file(root, "candidate/html-home-2/normalized.html", "<!doctype html>\r\n<!--home-->完整");
    file(root, "reference/html-home-1/normalized.html", "<!doctype html>\r\n<!--button-->完整");
    assert.equal(
      summarizeNuxtUiWholeHtml(root).wholeHtmlEqual,
      false,
      "button authority cannot bless home",
    );
  }));

